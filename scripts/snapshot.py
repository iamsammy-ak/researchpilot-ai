"""Fetch the two demo corpora from the keyless arXiv API and store them under demo/corpora/.

arXiv metadata (titles, authors, dates, categories and abstracts) is released under CC0 1.0, so the
snapshot can ship with the repository. Requests are spaced at least three seconds apart and cached
in .cache/arxiv/. If arXiv cannot be reached, the script writes clearly labelled synthetic
placeholder records instead (kind = "synthetic") so the app still runs, and says so.

    python scripts/snapshot.py [--force]
"""

from __future__ import annotations

import json
import random
import sys
import time
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from researchpilot.arxiv import ArxivClient, ArxivError  # noqa: E402

CORPORA_DIR = Path(__file__).resolve().parent.parent / "demo" / "corpora"
RETRY_BACKOFF_S = (20, 60, 0)  # arXiv answers HTTP 429 when busy: wait, then try again

TOPICS = [
    {
        "slug": "rag-evaluation",
        "name": "Retrieval-augmented generation evaluation",
        "query": 'abs:"retrieval augmented generation" AND (abs:evaluation OR abs:benchmark)',
        "max_results": 50,
    },
    {
        "slug": "battery-soh",
        "name": "Battery state-of-health estimation",
        "query": 'abs:"state of health" AND abs:battery AND (abs:estimation OR abs:prediction)',
        "max_results": 50,
    },
]


def synthetic_placeholders(topic: dict, n: int = 40, seed: int = 7) -> list[dict]:
    """Labelled stand-ins used only when arXiv is unreachable. They are not real papers."""
    rng = random.Random(seed)
    words = topic["name"].lower().split()
    methods = ["a transformer model", "a gradient-boosted baseline", "a Gaussian process", "a graph network",
               "a hybrid physics-informed model", "an ensemble of regressors"]
    records = []
    for i in range(n):
        method = rng.choice(methods)
        year = rng.randint(2019, 2025)
        records.append(
            {
                "arxiv_id": f"synthetic-{i + 1:03d}",
                "title": f"[Synthetic placeholder] {topic['name']} with {method} ({i + 1})",
                "authors": [f"Placeholder Author {rng.randint(1, 15)}", f"Placeholder Author {rng.randint(16, 30)}"],
                "published": f"{year}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}",
                "updated": "",
                "categories": [rng.choice(["cs.CL", "cs.LG", "eess.SY", "cs.IR"])],
                "abstract": (
                    f"Synthetic placeholder text, not a real abstract. This record stands in for a study on "
                    f"{' '.join(words)} that uses {method} and reports results on a public benchmark."
                ),
                "url": "",
                "pdf_url": "",
                "kind": "synthetic",
            }
        )
    return records


def main(force: bool = False) -> int:
    CORPORA_DIR.mkdir(parents=True, exist_ok=True)
    client = ArxivClient(timeout=90)
    for topic in TOPICS:
        out = CORPORA_DIR / f"{topic['slug']}.json"
        if out.exists() and not force:
            print(f"skip   {out.name}: already present (use --force to refetch)")
            continue
        synthetic, papers = False, []
        for attempt, backoff in enumerate(RETRY_BACKOFF_S, start=1):
            try:
                papers = client.search(topic["query"], max_results=topic["max_results"])
                if papers:
                    break
                raise ArxivError("no results")
            except ArxivError as exc:
                print(f"WARN   {topic['slug']} attempt {attempt}: {str(exc)[:120]}")
                if backoff:
                    time.sleep(backoff)
        if not papers:
            print(f"WARN   {topic['slug']}: arXiv unreachable. Writing synthetic placeholders instead.")
            papers, synthetic = synthetic_placeholders(topic), True
        payload = {
            "slug": topic["slug"],
            "name": topic["name"],
            "query": topic["query"],
            "fetched_at": date.today().isoformat(),
            "source": "Synthetic placeholders (arXiv was unreachable)" if synthetic else "arXiv API",
            "license": "Synthetic, generated by scripts/snapshot.py" if synthetic else "arXiv metadata, CC0 1.0",
            "synthetic": synthetic,
            "papers": papers,
        }
        out.write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"saved  {out.name}: {len(papers)} records" + (" (synthetic)" if synthetic else ""))
    print(f"arXiv requests made: {client.requests_made}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(force="--force" in sys.argv))
